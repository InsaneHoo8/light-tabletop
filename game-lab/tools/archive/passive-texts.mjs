import fs from 'node:fs';

const path = 'game-lab/arena/cards.js';
let src = fs.readFileSync(path, 'utf8').replace(/\r\n/g, '\n');

const PASSIVES = {
  mirai: 'Обмен активами: раз за ход меняется артефактом с любым игроком, не тратя действие. Сначала забирает артефакты киберпанка.',
  hrom: 'Пока держится щит, способности и артефакты стоят на единицу меньше.',
  glyuk: 'Если рука способностей пуста, возвращает две карты без действия.',
  borya: 'За каждые две недостающие энергии прибавляет единицу к своему урону и получает на единицу больше.',
  lyusya: 'Нанеся урон по нескольким целям, получает по единице менталки, энергии и здоровья.',
  grigori: 'Держа артефакты: один даёт плюс урон, два усиливают лечение, три снижают получаемый урон.',
  mag: 'Обмен даёт и энергию, и способность, причём карту маг выбирает сам.',
  grog: 'При двадцати здоровья способности дешевле, при шестнадцати лечение сильнее, при восьми урон больше.',
  zhulien: 'Обычной атакой может украсть артефакт вместо удара.',
  omnis: 'Артефакты чужих миров стоят на одну менталку меньше.',
  heil: 'Складывает два щита, в сумме до десяти единиц.',
  etkora: 'Ворованные способности держит сверх лимита руки, но не больше шести.'
};

for (const [id, text] of Object.entries(PASSIVES)) {
  const at = src.indexOf(`id: '${id}'`);
  if (at < 0) throw new Error('нет персонажа ' + id);
  const end = src.indexOf('abilities: [', at);
  let block = src.slice(at, end);
  if (/passive:/.test(block)) {
    block = block.replace(/passive: '[^']*',/, `passive: '${text}',`);
  } else {
    block = block.replace(/(handLimit: \d+,)/, `$1 passive: '${text}',`);
  }
  src = src.slice(0, at) + block + src.slice(end);
}

fs.writeFileSync(path, src, 'utf8');
console.log('пассивки записаны в данные');
