function findKey(name) {
  const keys = Object.keys(MAP).sort((a, b) => b.length - a.length);
  for (const k of keys) if (name.includes(k)) return k;
  return null;
}

const renamed = [];
const unknown = [];

for (const f of fs.readdirSync(MD_DIR).filter((x) => x.endsWith('.md'))) {
  const key = findKey(f);
  if (!key) { unknown.push(f); continue; }
  const base = f.replace(/\.md$/, '');
  const safeEssence = MAP[key].replace(/[:*?"<>|]/g, ' ').replace(/\s+/g, ' ').trim();
  const newBase = safeEssence + ' — ' + base;
  fs.renameSync(path.join(MD_DIR, f), path.join(MD_DIR, newBase + '.md'));
  const docxOld = path.join(DOCX_DIR, base + '.docx');
  const docxNew = path.join(DOCX_DIR, newBase + '.docx');
  if (fs.existsSync(docxOld)) fs.renameSync(docxOld, docxNew);
  renamed.push(newBase);
}

console.log('переименовано: ' + renamed.length);
