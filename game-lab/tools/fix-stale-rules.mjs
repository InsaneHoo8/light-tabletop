import fs from 'node:fs';

/* 1. Правила: актуальная формулировка про щиты */
const rp = 'game-lab/tools/gen-rules-doc.mjs';
let r = fs.readFileSync(rp, 'utf8').replace(/\r\n/g, '\n');
let n = 0;

function repR(old, neu, label) {
  if (!r.includes(old)) throw new Error('НЕ НАЙДЕНО: ' + label);
  r = r.replace(old, neu);
  n++;
  console.log('ok: ' + label);
}

repR(
  "add('Щит принимает урон вместо здоровья. Щиты не стакаются: на персонаже действует только один щит, и новый заменяет старый, только если он больше. Складывать два щита нельзя.');",
  "add('Щит принимает урон вместо здоровья. Щиты не стакаются: у персонажа одна активная карта щита, и пока она не сброшена, новую ставить нельзя.');",
  'правила: щит не стакается'
);

repR(
  "add('У Люси и Омниса ёмкость шесть, у остальных пять. У них действует одна карта щита: новая встаёт, только если она крепче прежней.');",
  "add('У Люси и Омниса ёмкость шесть, у Хейла десять, у остальных пять. У всех, кроме Хейла, одна карта щита: пока щит держится, новую карту щита ставить нельзя.');",
  'правила: ёмкость и запрет второй карты'
);

fs.writeFileSync(rp, r, 'utf8');

/* 2. Ход игроков: та же правка */
const cp = 'game-lab/tools/gen-core-docs.mjs';
let c = fs.readFileSync(cp, 'utf8').replace(/\r\n/g, '\n');
const old = "  hod.push('Щит держится, пока его не разрушат. Щиты не стакаются: действует одна карта щита, новая встаёт, только если она крепче. Исключение — Хейл, он складывает две карты. Потолок щита у каждого свой и записан в карточке.');";
const neu = "  hod.push('Щит держится, пока его не разрушат. Щиты не стакаются: у персонажа одна активная карта щита, и пока щит держится, новую карту щита ставить нельзя. Исключение — Хейл, он складывает две карты. Потолок щита у каждого свой и записан в карточке.');";
if (!c.includes(old)) throw new Error('НЕ НАЙДЕНО: ход игроков');
c = c.replace(old, neu);
fs.writeFileSync(cp, c, 'utf8');
console.log('ok: ход игроков');

/* 3. Справочник: лимит артефактов больше не ограничивает руку */
const dp = 'game-lab/docs/Промты для нейронки/Технические правила работы.md';
let d = fs.readFileSync(dp, 'utf8').replace(/\r\n/g, '\n');
const oldD = 'лимит руки способностей, лимит руки артефактов, ёмкость щита';
const newD = 'лимит руки способностей, ёмкость щита';
if (d.includes(oldD)) {
  d = d.replace(oldD, newD);
  fs.writeFileSync(dp, d, 'utf8');
  console.log('ok: справочник про лимит артефактов');
}

console.log('правок: ' + n);
