import fs from 'node:fs';

const rulesPath = 'game-lab/docs/Промты для нейронки/Правила и механики — всё.md';
let rules = fs.readFileSync(rulesPath, 'utf8');

const shieldSection = `## Щиты
Щит — временный запас, который принимает урон вместо здоровья. Щиты не стакаются: на персонаже в любой момент действует только один щит.
Если приходит новый щит и он больше текущего, он заменяет старый. Если меньше или равен — ничего не меняется, прежний щит остаётся. Складывать два щита в один нельзя никакими способами.
Щит держится до начала следующего хода своего владельца, если в описании способности не сказано иное.
Пробивающий урон проходит сквозь щит прямо в здоровье и щит при этом не расходует.
`;

if (!rules.includes('## Щиты')) {
  rules = rules.replace('## Порядок расчёта', shieldSection + '\n## Порядок расчёта');
} else {
  rules = rules.replace(/## Щиты[\s\S]*?(?=\n## )/, shieldSection + '\n');
}

rules = rules.replace(
  'Сначала срабатывает щит, потом урон идёт в здоровье.',
  'Сначала срабатывает щит, потом урон идёт в здоровье. Щит принимает только непробивающий урон: пробивающий проходит мимо щита и не тратит его.'
);

fs.writeFileSync(rulesPath, rules, 'utf8');
console.log('правила: раздел про щиты добавлен');

const hodPath = 'game-lab/docs/Игровой процесс/Ход игроков.md';
let hod = fs.readFileSync(hodPath, 'utf8');
if (!hod.includes('Щиты не стакаются')) {
  hod += '\nЩит — временный запас, который принимает урон вместо здоровья. Щиты не стакаются: на персонаже действует только один щит, и новый заменяет старый, только если он больше. Пробивающий урон проходит сквозь щит и не расходует его.\n';
  fs.writeFileSync(hodPath, hod, 'utf8');
  console.log('ход игроков: строка про щиты добавлена');
}
