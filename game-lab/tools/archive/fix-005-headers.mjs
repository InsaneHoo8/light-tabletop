/* Правит шапку отчётов патча 0.0.5: дата словами и описание изменений. */

import fs from 'node:fs';
import path from 'node:path';

const MD_DIR = 'game-lab/docs/Симуляция игр ботяр/Патч 0.0.5';
const DOCX_DIR = 'C:\\Users\\InsaneHoo8\\Desktop\\Лайтовая настолка\\Симуляция игр ботяр\\Патч 0.0.5';

const NEW_DATE = 'Симуляция проведена в патче ноль.ноль.пять от двадцать второго ноября две тысячи двадцать шестого года.';
const NEW_WHAT = [
  'Что в патче: щиты не стакаются, лимит артефактов снят, переработаны Люся, Хром, Боря и Омнис.',
  '',
  '- пока активна карта щита, новую ставить нельзя; у Хейла две карты, у остальных одна.',
  '- лимит руки артефактов снят у всех.',
  '- Люся: пассивка даёт артефакт за урон по двум и более целям, токсичный коммент на один урон, хайповый взрыв на три, охота на один урон и лечение по единице за цель, стрим отнимает по единице, донатный щит даёт шесть при двух артефактах и три иначе, отмена на четыре и сбрасывает половину артефактов.',
  '- Хром: ёмкость щита пять, пассивка со скидкой при активном щите, титановое покрытие на пять, шокер отнимает одну энергию.',
  '- Боря: базовый урон один, при недостаче двух энергии плюс один, при недостаче четырёх плюс два и плюс один получаемый урон.',
  '- Омнис: берёт два артефакта за действие.',
  '- стандартная симуляция идёт со случайным стилем ботов в каждой партии.'
];

let changed = 0;
for (const f of fs.readdirSync(MD_DIR).filter((x) => x.endsWith('.md'))) {
  const file = path.join(MD_DIR, f);
  let text = fs.readFileSync(file, 'utf8');

  text = text.replace(/^Симуляция проведена в патче.*$/m, NEW_DATE);

  /* заменяем блок «что в патче» до первого раздела */
  const startMarker = 'Что в патче:';
  const idx = text.indexOf(startMarker);
  if (idx >= 0) {
    const afterIdx = text.indexOf('\n## ', idx);
    const tail = afterIdx >= 0 ? text.slice(afterIdx) : '';
    const head = text.slice(0, idx);
    text = head + NEW_WHAT.join('\n') + '\n' + tail;
  }

  fs.writeFileSync(file, text, 'utf8');
  changed++;
}
console.log('исправлено отчётов: ' + changed);
