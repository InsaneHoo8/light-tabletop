import fs from 'node:fs';

const p = 'game-lab/tools/desc-from-ops.mjs';
let s = fs.readFileSync(p, 'utf8').replace(/\r\n/g, '\n');

function rep(old, neu, label) {
  if (!s.includes(old)) throw new Error('не найдено: ' + label);
  s = s.replace(old, neu);
  console.log('ok: ' + label);
}

/* форма для винительного падежа после глагола */
rep(`const ONE = (n) => plural(n, 'единица', 'единицы', 'единиц');`,
    `const ONE = (n) => plural(n, 'единица', 'единицы', 'единиц');
const ACC = (n) => (n === 1 ? 'одну единицу' : NUM(n) + ' ' + ONE(n));
const DAT = (n) => (n === 1 ? 'одной единицы' : NUM(n) + ' ' + ONE(n));`,
    'падежные формы');

/* урон: один урон вместо один урона */
rep(`      if (w === 'self') return \`при этом получает \${NUM(n)} урона\`;`,
    `      if (w === 'self') return \`при этом получает \${n === 1 ? 'один урон' : NUM(n) + ' урона'}\`;`,
    'самоурон');

rep(`      if (w === 'others') return \`наносит по \${NUM(n)} урона всем остальным\`;`,
    `      if (w === 'others') return \`наносит по \${NUM(n)} урона всем остальным\`;`,
    'урон по всем');

/* лечение */
rep(`        return \`восстанавливает \${NUM(n)} \${ONE(n)} здоровья\`;`,
    `        return \`восстанавливает \${ACC(n)} здоровья\`;`,
    'лечение себя');

rep(`      return \`восстанавливает \${NUM(n)} \${ONE(n)} здоровья выбранному игроку\`;`,
    `      return \`восстанавливает \${ACC(n)} здоровья выбранному игроку\`;`,
    'лечение другого');

/* энергия и менталка */
rep(`      if (n >= 0) return \`даёт \${NUM(n)} \${ONE(n)} энергии\`;
      return \`отнимает \${NUM(-n)} \${ONE(-n)} энергии\`;`,
    `      if (n >= 0) return \`даёт \${ACC(n)} энергии\`;
      return \`отнимает \${ACC(-n)} энергии\`;`,
    'энергия');

rep(`      if (n >= 0) return \`даёт \${NUM(n)} \${ONE(n)} менталки\`;
      return \`отнимает \${NUM(-n)} \${ONE(-n)} менталки\`;`,
    `      if (n >= 0) return \`даёт \${ACC(n)} менталки\`;
      return \`отнимает \${ACC(-n)} менталки\`;`,
    'менталка');

/* прочее с «на одну единицу» */
rep(`      return \`забирает \${NUM(n)} \${ONE(n)} здоровья у цели и восстанавливает столько же себе\`;`,
    `      return \`забирает \${ACC(n)} здоровья у цели и восстанавливает столько же себе\`;`,
    'кража здоровья');

rep(`      return \`прибавляет \${NUM(n)} \${ONE(n)} к урону следующей атаки\`;`,
    `      return \`прибавляет \${ACC(n)} к урону следующей атаки\`;`,
    'прибавка к урону');

rep(`      return \`цель бьёт слабее на \${NUM(n)} \${ONE(n)}\`;`,
    `      return \`цель бьёт слабее на \${ACC(n)}\`;`,
    'ослабление');

rep(`      return \`снижает получаемый урон на \${NUM(n)} \${ONE(n)} на \${NUM(op.turns || 1)} хода, но не ниже одной единицы\`;`,
    `      return \`снижает получаемый урон на \${ACC(n)} на \${NUM(op.turns || 1)} хода, но не ниже одной единицы\`;`,
    'снижение урона');

rep(`      return \`повышает здоровье и его максимум на \${NUM(n)} \${ONE(n)}\`;`,
    `      return \`повышает здоровье и его максимум на \${ACC(n)}\`;`,
    'прирост здоровья');

fs.writeFileSync(p, s, 'utf8');
